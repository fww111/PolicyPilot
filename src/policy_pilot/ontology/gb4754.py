def normalize_industry(text: str) -> tuple[str, str] | None:
    """自由行业表述 -> (国标代码, 国标名)。无法归一返回 None。

    匹配策略：别名精确 > 别名包含（按别名长度降序，长词优先）> 国标名包含。
    """
    if not text:
        return None
    t = text.strip().upper()
    # 代码直查路径：输入本身是国标代码（如 R83 / I65 / C39）
    import re as _re
    m = _re.match(r"^([A-T])(\d{2})$", t)
    if m:
        code = m.group(0)
        if code in GB_MAJOR:
            return code, GB_MAJOR[code]
        if m.group(1) in GB_CATEGORIES:
            return m.group(1), GB_CATEGORIES[m.group(1)]
    # 纯门类字母（如 R -> 文化、体育和娱乐业）
    if t in GB_CATEGORIES:
        return t, GB_CATEGORIES[t]
    for alias in sorted(_ALIASES, key=len, reverse=True):
        if alias.upper() in t:
            code = _ALIASES[alias]
            return code, GB_MAJOR.get(code) or GB_CATEGORIES.get(code, code)
    for code, name in {**GB_MAJOR, **GB_CATEGORIES}.items():
        if name in text or text in name:
            return code, name
    return None


def categories_for_match(text: str) -> list[str]:
    """行业表述 -> 匹配种子候选（含原词与国标名，双路命中）。"""
    out = [f"行业:{text}"] if text else []
    norm = normalize_industry(text or "")
    if norm:
        out.append(f"行业:{norm[1]}")
        out.append(f"行业:{norm[0]}")
    return out
